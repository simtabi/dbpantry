#!/usr/bin/env bash
# shellcheck shell=bash
#
# Shared helpers for the dbpantry-pg s6 init stages.

set -euo pipefail

# Generated state lives under /run, which is tmpfs. That is what lets the
# container run with a read-only root filesystem (SPEC section 9, design.md
# D-18) without a bespoke tmpfs mount for every directory we write to.
MDB_CONF_DIR=/run/mdb/conf.d
MDB_CERT_DIR=/run/mdb/certs

# User-supplied overrides are mounted here and stay read-only. PostgreSQL reads
# this directory AFTER the generated one, so a mounted file wins -- which is
# what SPEC section 13 requires.
MDB_OVERRIDE_CONF_DIR=/etc/postgresql/conf.d

MDB_INITDB_DIR=/docker-entrypoint-initdb.d
PGDATA_DIR="${PGDATA:-/var/lib/postgresql/data}"

export MDB_CONF_DIR MDB_CERT_DIR MDB_OVERRIDE_CONF_DIR MDB_INITDB_DIR PGDATA_DIR

# Every stage announces itself. The harness asserts the observed order in
# scripts/verify/10-s6-init-and-shutdown.sh, so these strings are load-bearing.
stage() { printf '[%s] %s\n' "$MDB_STAGE" "$*"; }

die() { printf '[%s] FATAL: %s\n' "${MDB_STAGE:-mdb}" "$*" >&2; exit 1; }

# Resolve a value that may be given directly or through the _FILE convention.
# SPEC decision 6: secrets travel as files, never as plain env.
resolve_secret() {
    local direct="${1:-}" file="${2:-}"
    if [[ -n "$file" ]]; then
        [[ -r "$file" ]] || die "secret file is not readable: $file"
        tr -d '\n' < "$file"
        return
    fi
    printf '%s' "$direct"
}

# Is the data directory already initialised?
pgdata_initialised() { [[ -s "$PGDATA_DIR/PG_VERSION" ]]; }

# true/false env helper.
is_true() {
    case "${1:-}" in
        true|TRUE|True|1|yes|YES|on|ON) return 0 ;;
        *) return 1 ;;
    esac
}

# -----------------------------------------------------------------------------
# Authentication hardening. Defined here, not in the stage script, because the
# first-run initdb.d hook needs the identical rules and a second copy would
# eventually disagree with the first.
# -----------------------------------------------------------------------------
# The file is generated whole rather than patched. Patching the initdb output
# means guessing at its exact spacing and missing whatever a future release
# adds; generating it means the rules are exactly what is written here.
#
# The split is the one SPEC section 10.1 specifies: peer for maintenance as the
# engine user, scram for app roles, on sockets as much as on TCP. An earlier
# attempt made ALL local auth peer, which locked application roles out of the
# socket entirely -- correct about trust, wrong about who peer is for.
harden_hba() {
    local hba="$1"
    [[ -f "$hba" ]] || return 0

    cat > "$hba" <<'EOF'
# Generated by dbpantry at container start. Do not edit; edit the image.
#
# SPEC section 9:    no trust or empty-password auth anywhere, localhost
#                    included.
# SPEC section 10.1: peer is reserved for make-driven maintenance as the
#                    engine user; app roles use scram, sockets included.

# Maintenance over the unix socket as the engine role. `docker exec` runs as
# root, which pg_ident maps to postgres, so peer still verifies a real OS
# identity rather than accepting anyone the way trust did.
local   all             postgres                                peer map=mdb

# Every other role authenticates, on the socket too.
local   all             all                                     scram-sha-256

# Loopback TCP is not special. This is the rule initdb ships as `trust`, and
# the reason a rotated password appeared to still work.
host    all             all             127.0.0.1/32            scram-sha-256
host    all             all             ::1/128                 scram-sha-256

# Replication.
local   replication     all                                     peer map=mdb
host    replication     all             127.0.0.1/32            scram-sha-256
host    replication     all             ::1/128                 scram-sha-256

# Everything else, including other containers on the toolkit network.
host    all             all             all                     scram-sha-256
EOF
    chmod 0600 "$hba"
    chown postgres:postgres "$hba" 2>/dev/null || true
}

# apply_tls_hba FILE
#
# The transport rules layered on a hardened pg_hba, one function for both the
# first-boot initdb hook and every later start, so the two cannot disagree
# (design.md D-74). They did: the hook only rewrote host to hostssl, so a FRESH
# volume under MDB_MTLS=true accepted connections without a client certificate
# until its first restart.
#
#   MDB_TLS_ENFORCE  every TCP rule becomes hostssl; plaintext TCP is refused.
#   MDB_MTLS         (with enforcement) every hostssl scram rule also demands
#                    clientcert=verify-full: a certificate from the toolkit CA
#                    whose CN is the role being logged into.
#   MDB_PG_POOLER_ADDR
#                    the pooler's fixed address, set by gen-compose. Under mTLS
#                    it gets its own rule, first: clientcert=verify-ca plus
#                    scram. The pooler logs in as every application role, so a
#                    CN-equals-role check cannot hold for it; its certificate
#                    must still come from the toolkit CA, and each role's
#                    password is still checked. PostgreSQL's map= option, which
#                    could otherwise relax the CN match, is not allowed with
#                    scram-sha-256.
apply_tls_hba() {
    local hba="$1"
    [[ -f "$hba" ]] || return 0
    is_true "${MDB_TLS_ENFORCE:-false}" || return 0
    sed -i 's/^host\([[:space:]]\)/hostssl\1/' "$hba"
    is_true "${MDB_MTLS:-false}" || return 0
    sed -i 's/^hostssl\(.*\)scram-sha-256$/hostssl\1scram-sha-256 clientcert=verify-full/' "$hba"
    if [[ -n "${MDB_PG_POOLER_ADDR:-}" ]]; then
        # Before the first hostssl rule: pg_hba is first-match.
        awk -v addr="$MDB_PG_POOLER_ADDR" '
            !done && /^hostssl[[:space:]]/ {
                print "# The pooler: a toolkit-CA certificate (its CN is not a role) plus the role password."
                printf "hostssl all             all             %-23s scram-sha-256 clientcert=verify-ca\n", addr
                done = 1
            }
            { print }' "$hba" > "$hba.mdb" && cat "$hba.mdb" > "$hba" && rm -f "$hba.mdb"
    fi
}

# The ident map lets root -- which is what `docker exec` runs as -- act as the
# postgres role over the socket. Peer still verifies a real OS identity, which
# trust did not do at all; this narrows it to a named user rather than anyone.
write_ident_map() {
    local ident="$1"
    [[ -f "$ident" ]] || return 0
    grep -q '^mdb[[:space:]]' "$ident" 2>/dev/null && return 0
    {
        printf '\n# dbpantry: allow container maintenance as the engine role.\n'
        printf '# MAPNAME   SYSTEM-USERNAME   PG-USERNAME\n'
        printf 'mdb        root              postgres\n'
        printf 'mdb        postgres          postgres\n'
    } >> "$ident"
}
