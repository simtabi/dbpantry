package engine

import (
	"fmt"
	"io"
	"sort"
	"strconv"

	"go.yaml.in/yaml/v3"
)

// HelmEngine is the part of a chart engine block (deploy/helm/dbpantry
// values.yaml, engines.<name>) that restates a descriptor fact. The chart
// keeps its own operational defaults (storage, memory, probes); these fields
// it may only copy (F3).
type HelmEngine struct {
	Image         string            `yaml:"image"`
	Tag           string            `yaml:"tag"`
	ImageRef      string            `yaml:"imageRef"`
	Port          int               `yaml:"port"`
	DataPath      string            `yaml:"dataPath"`
	PITRPath      string            `yaml:"pitrPath"`
	OverridesPath string            `yaml:"overridesPath"`
	SecretEnv     map[string]string `yaml:"secretEnv"`
}

// HelmFacts derives each implemented engine's chart facts from the manifest.
func (m Manifest) HelmFacts() map[string]HelmEngine {
	out := map[string]HelmEngine{}
	for _, e := range m.Implemented() {
		h := HelmEngine{
			Port:          e.Port,
			DataPath:      e.DataDir,
			PITRPath:      e.PITRRepoPath,
			OverridesPath: e.OverridesDir,
			SecretEnv:     map[string]string{},
		}
		if e.Publish == "reference" {
			// Referenced, not rebuilt: the chart runs the pinned upstream image.
			h.ImageRef = e.Bases[e.DefaultVersion]
		} else {
			h.Image = "dbpantry-" + e.Name
			h.Tag = e.DefaultVersion
		}
		if e.RootPasswordEnv != "" {
			h.SecretEnv[e.RootPasswordEnv] = e.RootSecret
		}
		out[e.Name] = h
	}
	return out
}

// WriteHelm writes the facts as a values fragment (engines.<name>.*).
func (m Manifest) WriteHelm(w io.Writer) error {
	if _, err := fmt.Fprintf(w, "# Generated by `dbpantry manifest -o helm` from engines/*/engine.conf.\n"); err != nil {
		return err
	}
	enc := yaml.NewEncoder(w)
	enc.SetIndent(2)
	if err := enc.Encode(map[string]any{"engines": m.HelmFacts()}); err != nil {
		return err
	}
	return enc.Close()
}

// CheckHelm compares a chart values file with the manifest and returns every
// disagreement: an engine the chart has and the manifest does not implement
// (or the reverse), and every restated fact that differs.
func (m Manifest) CheckHelm(values []byte) ([]string, error) {
	var doc struct {
		Engines map[string]yaml.Node `yaml:"engines"`
	}
	if err := yaml.Unmarshal(values, &doc); err != nil {
		return nil, fmt.Errorf("values file: %w", err)
	}
	if len(doc.Engines) == 0 {
		return nil, fmt.Errorf("values file has no engines: map")
	}
	want := m.HelmFacts()
	var problems []string
	for _, name := range sortedKeys(want) {
		node, ok := doc.Engines[name]
		if !ok {
			problems = append(problems, fmt.Sprintf("engines.%s: implemented in engines/ but missing from the chart", name))
			continue
		}
		var got HelmEngine
		if err := node.Decode(&got); err != nil {
			problems = append(problems, fmt.Sprintf("engines.%s: %v", name, err))
			continue
		}
		w := want[name]
		cmp := func(field, gotV, wantV string) {
			if gotV != wantV {
				problems = append(problems, fmt.Sprintf("engines.%s.%s is %q, the descriptor says %q", name, field, gotV, wantV))
			}
		}
		cmp("image", got.Image, w.Image)
		cmp("tag", got.Tag, w.Tag)
		cmp("imageRef", got.ImageRef, w.ImageRef)
		cmp("port", strconv.Itoa(got.Port), strconv.Itoa(w.Port))
		cmp("dataPath", got.DataPath, w.DataPath)
		cmp("pitrPath", got.PITRPath, w.PITRPath)
		cmp("overridesPath", got.OverridesPath, w.OverridesPath)
		for _, k := range sortedKeys(w.SecretEnv) {
			cmp("secretEnv."+k, got.SecretEnv[k], w.SecretEnv[k])
		}
	}
	for name := range doc.Engines {
		if _, ok := want[name]; !ok {
			problems = append(problems, fmt.Sprintf("engines.%s: in the chart but not an implemented engine in engines/", name))
		}
	}
	sort.Strings(problems)
	return problems, nil
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
